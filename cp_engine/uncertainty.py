"""Validation-based uncertainty estimate of a Route-A heat capacity.

Every ingredient of a Route-A result (pure-component correlations, the excess model of each liquid
phase, the ideal-mixing fallback, the suspension mixing rule, the pressure correction, the real-gas
residual) has been compared with published data in validation/.  data/model_uncertainty.json holds
those mean absolute deviations (generated by tools/make_uncertainty_table.py).  The estimate is

    u(C_p) = √( Σ_k u_k² ),   u_k = (deviation of ingredient k, %) × (its contribution to C_p)

i.e. the contributions are treated as independent.  It is an *expected deviation from measurements*
based on this project's own validation, not a formal metrological uncertainty.  Inside a phase change
the location of the phase boundary (freezing point ± 2.5 K, bubble point ± 0.3 K) dominates; that part
is reported as a note, not included in the number.
"""
from __future__ import annotations

import json
import math
from functools import lru_cache
from pathlib import Path
from typing import Any

from .database import P_ATM, default_data_dir


@lru_cache(maxsize=2)
def _table(data_dir: str | None = None) -> dict[str, Any]:
    path = Path(data_dir or default_data_dir()) / "model_uncertainty.json"
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def estimate(model, bd) -> dict[str, Any] | None:
    """Uncertainty of the Route-A result `bd` (CpBreakdown) of SystemModel `model`."""
    tab = _table()
    if not tab or bd.total == 0:
        return None
    T = bd.T if bd.kind == "point" else 0.5 * (bd.T1 + bd.T2)
    entries = model.split(T)
    parts: list[tuple[str, float, str]] = []          # (label, u in J/K, validation row)

    def add(label: str, cp: float, e: dict | None) -> None:
        if e is None or cp == 0:
            return
        parts.append((label, abs(cp) * e["value"] / 100.0, e["row"]))

    # 1. pure-component correlations
    by_comp: dict[tuple[str, str], float] = {}
    for _, k, state, n in entries:
        if n <= 0:
            continue
        phase = "solid" if state == "dissolved" else state
        by_comp[(k, phase)] = by_comp.get((k, phase), 0.0) + n * model._pure_cp(k, state, T)
    for (k, phase), cp in by_comp.items():
        e = tab["pure"].get(f"{k}|{phase}".lower(), tab["pure_default"])
        add(f"{model.comps[k].name} ({phase}) heat capacity", cp, e)

    # 2. liquid phases: excess model or ideal-mixing fallback
    for gname, comp_n in model._liquid_groups(entries).items():
        members = [m for m in model.groups[gname] if comp_n.get(m, 0.0) > 0]
        if len(members) < 2:
            continue
        cp_group = sum(n * model._pure_cp(m, "liquid", T) for m, n in comp_n.items()
                       if any(st == "liquid" for nm, kk, st, nn in entries if nm == gname and kk == m))
        ntot = sum(comp_n.values())
        pair_keys = ["+".join(sorted((a, b))) for i, a in enumerate(members) for b in members[i + 1:]]
        nrtl = model._nrtl(tuple(model.groups[gname]))
        found = False
        for key in pair_keys:
            if key in tab["mixtures"]:
                add(f"{gname}: mixture model for {key}", cp_group, tab["mixtures"][key])
                found = True
            elif key in tab["mixtures_cpE_abs"] and nrtl is not None:
                e = tab["mixtures_cpE_abs"][key]
                parts.append((f"{gname}: Cp^E model for {key}", ntot * e["value"], e["row"]))
                found = True
        if not found:
            if nrtl is None:
                add(f"{gname}: ideal mixing (no binary parameters)", cp_group, tab["ideal_fallback"])
            else:
                add(f"{gname}: excess model (pair not validated; ideal-fallback deviation used)", cp_group,
                    tab["ideal_fallback"])

    # 3. suspensions (mass-weighted mixing rule, Model II)
    solids = any(st == "solid" and n > 0 for _, _, st, n in entries)
    liquids = any(st in ("liquid", "dissolved") and n > 0 for _, _, st, n in entries)
    if solids and liquids:
        add("solid–liquid suspension (Model II mixing rule)", bd.ideal + bd.excess, tab["suspension"])

    # 4. pressure correction of condensed phases and real-gas residual
    if abs(model.P - P_ATM) > 1e4:
        cond = sum(n * model._pure_cp(k, st, T) for _, k, st, n in entries if n > 0 and st != "gas")
        add("pressure correction (Tait equation)", cond, tab["pressure_correction"])
    gas_cp = sum(n * model._pure_cp(k, st, T) for _, k, st, n in entries if n > 0 and st == "gas")
    if gas_cp and model.gas_eos != "ideal" and model.P > 2e5:
        add(f"real-gas residual Cp ({model.gas_eos} equation of state)", gas_cp, tab["gas_residual_PR"])

    u = math.sqrt(sum(p[1] ** 2 for p in parts))
    out = {"relative_percent": 100.0 * u / abs(bd.total),
           "absolute_J_per_kgK": u / bd.mass,
           "contributions": [{"source": lbl, "percent_of_cp": 100.0 * v / abs(bd.total), "validation": row}
                             for lbl, v, row in sorted(parts, key=lambda p: -p[1])],
           "method": "√Σ u_k²; u_k = mean deviation of ingredient k in this project's validation × its share of Cp",
           "notes": []}
    if abs(bd.latent) > 1e-6 * abs(bd.total):
        pb = tab.get("phase_boundaries", {})
        fp, bp = pb.get("freezing_point_K", {}), pb.get("bubble_point_K", {})
        out["notes"].append(
            "Inside a phase change the latent part also depends on where the phase boundary lies "
            f"(validated: freezing points ± {fp.get('value', float('nan')):.1f} K, bubble points "
            f"± {bp.get('value', float('nan')):.2f} K); that is NOT included in the number above.")
    return out
