"""Build data/model_uncertainty.json from the validation results (validation/results/summary.csv).

Every number the engine uses to estimate the uncertainty of a result is a measured deviation from
this project's own validation against published data – nothing is assumed except where stated
("default" entries, used only for ingredients with no validation row).

Run after validation/run_all.py:   python tools/make_uncertainty_table.py
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent


def main() -> None:
    d = pd.read_csv(ROOT / "validation" / "results" / "summary.csv")
    d = d[d.status == "ok"]

    def pick(case, system, contains, metric="AARD %"):
        r = d[(d.case.astype(str) == case) & (d.system == system) & d.quantity.str.contains(contains, regex=False)
              & (d.metric == metric)]
        if len(r) != 1:
            raise SystemExit(f"expected one row for {case} / {system} / {contains}, found {len(r)}")
        r = r.iloc[0]
        return {"value": round(float(r["mean"]), 4), "max": round(float(r["max"]), 4), "N": int(r.N),
                "row": f"case {case}: {system}: {r.quantity}"}

    pure = {}
    for _, r in d[(d.case.astype(str) == "1") & (d.metric == "AARD %")].iterrows():
        if "1 atm" in r.quantity:
            key = f"{r.system}|liquid"
        elif "point values" in r.quantity:
            name, phase = r.system.split(" (")
            key = f"{name}|{phase.rstrip(')')}"
        elif "ideal gas" in r.system:
            key = f"{r.system.split(' (')[0]}|gas"
        else:
            continue
        pure[key.lower()] = {"value": round(float(r["mean"]), 4), "max": round(float(r["max"]), 4),
                             "N": int(r.N), "row": f"case 1: {r.system}: {r.quantity}"}

    c6 = d[d.case.astype(str) == "6"]
    pr = c6[c6.quantity.str.contains("from PR", regex=False)]
    tait = d[(d.case.astype(str) == "1") & d.quantity.str.contains("Tait pressure correction", regex=False)]
    nano = pick("3", "all nanofluids", "Model II")
    table = {
        "_meta": {"description": "Validation-based deviations used by cp_engine/uncertainty.py "
                                 "(mean absolute deviations from published data; generated by "
                                 "tools/make_uncertainty_table.py from validation/results/summary.csv).",
                  "unit": "percent unless stated"},
        "pure": pure,
        "pure_default": {"value": 2.0, "row": "default for a pure-component correlation with no validation row "
                                               "(assumed, not measured)"},
        "pressure_correction": {"value": round(float((tait["mean"] * tait.N).sum() / tait.N.sum()), 4),
                                "max": round(float(tait["max"].max()), 4), "N": int(tait.N.sum()),
                                "row": "case 1: Tait pressure correction, 5 liquids, 0.1-100 MPa"},
        "gas_residual_PR": {"value": round(float((pr["mean"] * pr.N).sum() / pr.N.sum()), 4),
                            "max": round(float(pr["max"].max()), 4), "N": int(pr.N.sum()),
                            "row": "case 6: 4 vapours, 0.5-10 MPa, ideal gas + Peng-Robinson residual"},
        "mixtures": {
            "methanol+water": pick("2", "methanol + water", "NRTL refitted to H^E"),
            "ethanol+toluene": pick("2", "ethanol + toluene", "NRTL fitted to VLE"),
            "glycerol+water": pick("2", "glycerol + water", "ideal fallback"),
            "nacl+water": pick("2", "NaCl + water (brine)", "INDEPENDENT"),
        },
        "mixtures_cpE_abs": {
            "ethanol+water": dict(pick("2b", "ethanol + water", "source paper held out, NRTL refitted",
                                       metric="RMSD J/(mol K)"), unit="J/(mol K) of mixture"),
        },
        "ideal_fallback": pick("2", "ethanol + toluene", "ideal mixture"),
        "suspension": nano,
        "phase_boundaries": {
            "bubble_point_K": {**pick("6", "ethanol + water", "NRTL VLE set", metric="|ΔT| K")},
            "freezing_point_K": {**pick("2b", "ice + water + ethanol", "freezing points", metric="|ΔT| K")},
        },
    }
    out = ROOT / "data" / "model_uncertainty.json"
    out.write_text(json.dumps(table, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print("written", out, f"({len(pure)} pure-component entries)")


if __name__ == "__main__":
    main()
