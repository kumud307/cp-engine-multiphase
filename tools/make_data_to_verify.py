"""Regenerate docs/DATA_TO_VERIFY.md from the "verify": true flags in the database.

Run from the project root:  python tools/make_data_to_verify.py
After checking a value against its primary source, correct it if needed, set "verify": false
and re-run this script.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from cp_engine.database import Database  # noqa: E402

items = Database(ROOT / "data").verify_items()


def category(item: str) -> str:
    if item.startswith(("n-octadecane.cp", "binary.nrtl", "binary.miscibility")):
        return "A"
    if ".alpha[" in item or ".kappa_T[" in item:
        return "B"
    if ".cp[gas]" in item or ".Tb " in item or ".dHvap" in item or ".critical" in item:
        return "C"
    if item.startswith(("Al2O3.dHfus", "SiO2.", "NaCl.dHfus")):
        return "D"
    return "E"


TITLES = {
    "A": ("Can change a Cp result directly",
          "Check these first. The miscibility flags decide whether a pair forms one liquid phase or two "
          "(with ideal mixing in each phase the Cp is the same either way; the flag matters for the "
          "excess part and for boiling)."),
    "B": ("Only affect Cp − Cv (Route C via Cv) and the Cv estimate",
          "Cp − Cv = Tvα²/κ_T. For solids this is below 1 % of Cp (e.g. Al₂O₃: 5 J/(kg K) of 773), so even a "
          "50 % error in α or κ_T changes Cp by under 1 %. For liquids it is 1–10 % of Cp, so a "
          "κ_T error matters only when Cp is computed from a measured Cv."),
    "C": ("Only used near or above the boiling point (vapour phase)",
          "Enthalpy of the vapour (T_b, ΔH_vap), ideal-gas Cp, and the critical constants used for the "
          "real-gas residual Cp. No effect on liquid, solid or slurry results."),
    "D": ("Only used for melting of oxides or salts (above 1000 K)", "Never reached in this project."),
    "E": ("Only used to convert volume fractions to masses", "No effect when the composition is given as mass or mole fractions."),
}

lines = [f"""# DATA TO VERIFY

Generated by `python tools/make_data_to_verify.py` from the `"verify": true` flags in `data/*.json`.
Full provenance of every dataset: `docs/DATA_SOURCES.md`.

## Status on 5 November 2026

**Verified against primary or authoritative sources** (flag cleared):
- Liquid Cp correlations: water, methanol, n-hexane, toluene, n-dodecane vs downloaded NIST SRD 69 tables; ethanol, acetone, glycerol, n-octadecane vs NIST measured values.
- Shomate Cp of Al₂O₃, CuO, SiO₂, NaCl: digit by digit vs NIST WebBook.
- Ice Cp, ρ, α, κ_T: IAPWS R10-06 equation of state (implemented and checked to 9 digits).
- Liquid densities: NIST fits; ethanol vs Lange (0.16 %); water Kell equation.
- Solid densities, NaCl solubility table and heat of solution: CRC values.
- NRTL ethanol–water and methanol–water (VLE sets): against the published table. Hᴱ-fitted sets: fitted by us to NIST ThermoML data.
- Tm, ΔH_fus, Tb, ΔH_vap of the organic liquids: NIST phase-change pages.
- κ_T(T) of water, methanol, n-hexane, toluene, n-dodecane: fitted to NIST; the pressure correction built on it matches NIST isotherms to 1.2 % up to 100 MPa.
- NaCl(aq) apparent molar heat capacity: fitted to Tromans et al. 2005; independent check 0.17 %; one inconsistent dataset excluded.
- Ideal-gas Cp of ethanol, methanol, acetone, n-hexane, toluene: vs NIST recommended values 200–1000 K (max 1.25 %).
- n-Octadecane: solid Cp and liquid density refitted to measurements (Fonseca 2014; Espeau & Céolin 2006); κ_T consistent with Kariznovi 2012; T_m and ΔH_fus confirmed by five later papers.
- Acetone–water NRTL: tested against measured γ∞ (25 % low, right T trend); predicts a spurious phase split above ≈ 360 K, which the engine now detects and warns about.
- Methanol + n-hexane: replaced the "partially miscible" flag by the measured coexistence curve (Trejo 2006). Methanol + n-dodecane immiscibility confirmed (Casás 2004).
- Ethanol + toluene: NRTL fitted to measured VLE (Chen 2012) and Cpᴱ (Vega-Maza 2011); NIST Antoine vapour pressures added.
- Vapour pressures of water, methanol, n-hexane: Antoine equations fitted to NIST SRD 69 saturation tables (≤ 0.8 %); acetone: NIST Antoine set.
- Critical constants and ω: NIST reference-EOS critical points (5 fluids), measured values for ethanol; ω from its definition. Acetone's T_c, P_c are NIST averages (flagged below).

**Corrected during verification:** acetone–water NRTL orientation (i/j swapped), glycerol Cp (4 % high),
ice Cp (1.4 % low), CuO valid range, solid densities, NaCl solubility table.

**Experimental validation data obtained** (no longer templates): NIST pure-fluid tables, NIST ThermoML
mixture data (Hᴱ, Cp, VLE, γ∞, LLE), NIST ideal-gas Cp, O'Hanley et al. 2012 nanofluid DSC data,
Lange's freezing points.

## Still open ({len(items)} flagged values)
"""]
for cat in "ABCDE":
    sel = [i for i in items if category(i) == cat]
    if not sel:
        continue
    title, why = TITLES[cat]
    lines.append(f"\n### {cat}. {title} ({len(sel)})\n\n{why}\n")
    lines += [f"- [ ] `{i}`" for i in sel]

lines.append("""

## Optional extra datasets (would strengthen validation further)

| Dataset | Where to look | Where to put it |
|---|---|---|
| Direct Cp of water + ethanol mixtures (298 K) | J. Chem. Thermodyn. / J. Chem. Eng. Data via the IITGN library (e.g. Ogawa & Murakami, Thermochim. Acta 1986; Gaulhofer, Kolbe & Gmehling, Fluid Phase Equilib. 1988) | `validation/data/water_ethanol_cp_exp.csv`; case 2 picks it up automatically |
| DSC apparent-Cp curve of an n-octadecane slurry or emulsion | Candidate: Zhang et al., *Fire* 2024, 7, 371 (doi:10.3390/fire7100371), n-octadecane nano-emulsion for battery cooling (open access, but the full text could not be downloaded here; check the paper's figures/tables for an apparent-Cp curve, melting range and latent heat) | Add a CSV and a comparison in `validation/case4_phase_change.py` |

## References to check before the manuscript is submitted

Confirmed from primary listings during this work:
- Zhou & Ni, Appl. Phys. Lett. 2008, 92, 093123 (cited as reference [3] in O'Hanley et al. 2012).
- O'Hanley et al., Adv. Mech. Eng. 2012, 181079, doi:10.1155/2012/181079.
- Green & Perry, Perry's Chemical Engineers' Handbook, 8th ed., McGraw-Hill 2008 (O'Hanley et al. reference [9]).
- Feistel & Wagner, J. Phys. Chem. Ref. Data 2006, 35, 1021 (IAPWS R10-06 reference [1]).
- All ThermoML papers: authors, title, journal and pages taken from the archive records (see `docs/DATA_SOURCES.md`).

Still marked `% VERIFY` in `manuscript/references.bib` (standard references whose details were not re-checked online):
- [ ] Renon & Prausnitz, AIChE J. 1968, 14, 135.
- [ ] Pak & Cho, Exp. Heat Transfer 1998, 11, 151.
- [ ] Xuan & Roetzel, Int. J. Heat Mass Transfer 2000, 43, 3701.
- [ ] Kell, J. Chem. Eng. Data 1975, 20, 97.
- [ ] Smith, Van Ness, Abbott & Swihart, 8th ed. 2018; Prausnitz, Lichtenthaler & de Azevedo, 3rd ed. 1999.
- [ ] Lange's Handbook of Chemistry (edition cited for the 1967 freezing-point table).
""")
out = ROOT / "docs" / "DATA_TO_VERIFY.md"
out.write_text("\n".join(lines), encoding="utf-8")
print(f"written {out}: {len(items)} open items")
